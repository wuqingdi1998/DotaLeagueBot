"""Правила регистрации игроков на клозы."""

UNSET_TIER_MESSAGE = (
    "У вас не установлен серверный тир, для его получения отправьте скриншот "
    "полной страницы с актуальным MMR и последними матчами @frokeng"
)


def can_register_for_close(tier_status: str | None) -> bool:
    """Разрешить регистрацию только игроку с подтверждённым серверным тиром."""
    return tier_status == "current"
